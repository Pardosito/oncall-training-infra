#!/usr/bin/env bash
# Writes the gitignored inputs of the aws overlay from the Terraform outputs (ARCHITECTURE §5.4):
#   k8s/overlays/aws/config.env   → ConfigMap oncall-config (app + injector)
#   k8s/overlays/aws/cluster.env  → ECR registry and ALB security group for the replacements
# Needs both stacks initialized (make targets do that). Never prints secrets: there are none.
set -euo pipefail

cd "$(dirname "$0")/.."
OVERLAY="k8s/overlays/aws"

outputs() { terraform -chdir="terraform/$1" output -json; }

echo "Reading Terraform outputs (foundation, cluster)..." >&2
foundation="$(outputs foundation)"
cluster="$(outputs cluster)"

# $(get <json> <name>) → value, or empty if the output doesn't exist yet.
get() { jq -r --arg k "$2" '.[$k].value // empty | if type == "string" then . else tojson end' <<<"$1"; }

require() {
  local value
  value="$(get "$1" "$2")"
  [ -n "$value" ] || { echo "error: terraform output '$2' is missing; apply its stack first" >&2; exit 1; }
  printf '%s' "$value"
}

sessions_table="$(require "$foundation" sessions_table)"
files_bucket="$(require "$foundation" files_bucket)"
faults_queue_url="$(require "$foundation" faults_queue_url)"
user_actions_queue_url="$(require "$foundation" user_actions_queue_url)"
mock_repo_url="$(jq -r '.ecr_repository_urls.value["mock-system"] // empty' <<<"$foundation")"
alb_sg="$(require "$cluster" alb_security_group_id)"
[ -n "$mock_repo_url" ] || { echo "error: ecr_repository_urls missing in foundation outputs" >&2; exit 1; }
ecr_registry="${mock_repo_url%%/*}"

# Outputs that only exist from M2 on. Until then the MVP config below applies (D-25, INF-139).
for later in state_machine_arn athena_workgroup glue_database cognito_user_pool_id cognito_client_id; do
  [ -n "$(get "$foundation" "$later")" ] || echo "note: no '$later' output yet (M2); not in config.env" >&2
done
[ -n "$(get "$cluster" redis_endpoint)" ] || echo "note: no 'redis_endpoint' output yet (M2); REDIS_URL not set" >&2

umask 077
cat >"$OVERLAY/config.env" <<CONF
# Generated by scripts/render-config.sh — do not edit, do not commit.
AWS_REGION=us-east-1
SESSIONS_TABLE=$sessions_table
FILES_BUCKET=$files_bucket
FAULTS_QUEUE_URL=$faults_queue_url
USER_ACTIONS_QUEUE_URL=$user_actions_queue_url
MOCK_NAMESPACE=mock
MOCK_HEALTH_URL_TEMPLATE=http://{service}.mock.svc.cluster.local:8080/health
MOCK_CLUSTER=kubernetes
STATS_MODE=athena
# MVP mode (ARCHITECTURE §15, INF-139): no Cognito, no Step Functions, no Redis. Removed in M2.
AUTH_MODE=dev
ALLOW_DEV_AUTH=true
ORCHESTRATION_MODE=direct
CONF

cat >"$OVERLAY/cluster.env" <<CONF
# Generated by scripts/render-config.sh — do not edit, do not commit.
ECR_REGISTRY=$ecr_registry
ALB_SECURITY_GROUP_ID=$alb_sg
CONF

echo "Wrote $OVERLAY/config.env and $OVERLAY/cluster.env" >&2
