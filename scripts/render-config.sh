#!/usr/bin/env bash
# Writes the gitignored inputs of the aws overlay from the Terraform outputs (ARCHITECTURE §5.4):
#   k8s/overlays/aws/config.env   → ConfigMap oncall-config (app + injector)
#   k8s/overlays/aws/cluster.env  → ECR registry and the api target group for the replacements
# Needs both stacks initialized (make targets do that). Never prints secrets: there are none.
set -euo pipefail

cd "$(dirname "$0")/.."
OVERLAY="k8s/overlays/aws"

outputs() { terraform -chdir="terraform/$1" output -json; }

echo "Reading Terraform outputs (foundation, cluster)..." >&2
foundation="$(outputs foundation)"
cluster="$(outputs cluster)"

# $(get <json> <name>) → value, or empty if the output doesn't exist yet.
get() { jq -r --arg k "$2" '.[$k].value // empty | if type == "string" then . else tojson end' <<<"$1"; }

require() {
  local value
  value="$(get "$1" "$2")"
  [ -n "$value" ] || { echo "error: terraform output '$2' is missing; apply its stack first" >&2; exit 1; }
  printf '%s' "$value"
}

sessions_table="$(require "$foundation" sessions_table)"
files_bucket="$(require "$foundation" files_bucket)"
faults_queue_url="$(require "$foundation" faults_queue_url)"
user_actions_queue_url="$(require "$foundation" user_actions_queue_url)"
mock_repo_url="$(jq -r '.ecr_repository_urls.value["mock-system"] // empty' <<<"$foundation")"
api_tg="$(require "$cluster" api_target_group_arn)"
[ -n "$mock_repo_url" ] || { echo "error: ecr_repository_urls missing in foundation outputs" >&2; exit 1; }
ecr_registry="${mock_repo_url%%/*}"

# Outputs that only exist from M2 on. Until then the MVP config below applies (D-25, INF-139).
for later in athena_workgroup glue_database; do
  [ -n "$(get "$foundation" "$later")" ] || echo "note: no '$later' output yet (M2); not in config.env" >&2
done
cognito_user_pool_id="$(get "$foundation" cognito_user_pool_id)"
cognito_client_id="$(get "$foundation" cognito_client_id)"
state_machine_arn="$(get "$foundation" state_machine_arn)"
# Step Functions runs the scenario (backend D-32); ORCHESTRATION_MODE=direct falls back to the MVP path (§15).
orchestration_mode="${ORCHESTRATION_MODE:-stepfunctions}"
case "$orchestration_mode" in
  direct) ;;
  stepfunctions)
    [ -n "$state_machine_arn" ] || { echo "error: ORCHESTRATION_MODE=stepfunctions needs the state_machine_arn output; run make foundation-apply" >&2; exit 1; } ;;
  *) echo "error: ORCHESTRATION_MODE must be direct or stepfunctions" >&2; exit 1 ;;
esac
redis_url="$(get "$cluster" redis_endpoint)"
[ -n "$redis_url" ] || echo "note: no 'redis_endpoint' output yet (M2); REDIS_URL not set" >&2

umask 077
cat >"$OVERLAY/config.env" <<CONF
# Generated by scripts/render-config.sh — do not edit, do not commit.
AWS_REGION=us-east-1
SESSIONS_TABLE=$sessions_table
FILES_BUCKET=$files_bucket
FAULTS_QUEUE_URL=$faults_queue_url
USER_ACTIONS_QUEUE_URL=$user_actions_queue_url
MOCK_NAMESPACE=mock
MOCK_HEALTH_URL_TEMPLATE=http://{service}.mock.svc.cluster.local:8080/health
MOCK_CLUSTER=kubernetes
ORCHESTRATION_MODE=$orchestration_mode
CONF
# Cognito (INF-031..033) once foundation has it; until then the MVP dev auth (INF-139).
if [ -n "$cognito_user_pool_id" ] && [ -n "$cognito_client_id" ]; then
  cat >>"$OVERLAY/config.env" <<CONF
AUTH_MODE=cognito
COGNITO_USER_POOL_ID=$cognito_user_pool_id
COGNITO_CLIENT_ID=$cognito_client_id
CONF
else
  printf 'AUTH_MODE=dev\nALLOW_DEV_AUTH=true\n' >>"$OVERLAY/config.env"
fi
# No CORS_ORIGINS: the HTTP API answers CORS for the site (D-33) and ignores the backend's headers.
[ -z "$state_machine_arn" ] || echo "STATE_MACHINE_ARN=$state_machine_arn" >>"$OVERLAY/config.env"
# ElastiCache (rediss://, D-09): the backend's lock, events and snapshots; the injector's events.
[ -z "$redis_url" ] || echo "REDIS_URL=$redis_url" >>"$OVERLAY/config.env"

cat >"$OVERLAY/cluster.env" <<CONF
# Generated by scripts/render-config.sh — do not edit, do not commit.
ECR_REGISTRY=$ecr_registry
API_TARGET_GROUP_ARN=$api_tg
CONF

echo "Wrote $OVERLAY/config.env and $OVERLAY/cluster.env" >&2
